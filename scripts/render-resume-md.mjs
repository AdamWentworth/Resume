import { writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import {
  additionalItems,
  availability,
  experienceBullets,
  github,
  headline,
  linkedIn,
  phone,
  profile,
  projectBullets,
  projectDates,
  skills,
} from './resume-document.mjs';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { resume } = await import(pathToFileURL(resolve(repoRoot, 'src/data/resume.ts')).href);
const outputPath = resolve(repoRoot, 'RESUME.md');

function list(items) {
  return items.join(', ');
}

function bullets(items) {
  return items.map((item) => `- ${item}`).join('\n');
}

function section(title, content) {
  return `## ${title}\n\n${content}`;
}

function projectEntry(project) {
  const date = projectDates.get(project.name) ?? 'Selected project';
  const projectLine = `### ${project.name} - ${project.role}`;
  const links = [
    project.href ? `[Repository](${project.href})` : null,
    project.phlosionDemoHref ? `[Demo on Phlosion](${project.phlosionDemoHref})` : null,
  ]
    .filter(Boolean)
    .join(' | ');

  const parts = [
    projectLine,
    '',
    `_${date}_`,
    '',
    `**Technologies:** ${list(project.technologies)}`,
    '',
    bullets(projectBullets.get(project.name) ?? project.proof.slice(0, 2).map((proof) => proof.text)),
  ];

  if (links) {
    parts.push('', links);
  }

  return parts.join('\n');
}

function experienceEntry(item) {
  return [
    `### ${item.title} - ${item.company}`,
    '',
    `_${item.location} | ${item.period}_`,
    '',
    `**Technologies:** ${list(item.technologies)}`,
    '',
    bullets(experienceBullets.get(item.title) ?? item.highlights.slice(0, 1)),
  ].join('\n');
}

const markdown = [
  '<!-- Generated by npm run resume:md. Edit src/data/resume.ts and scripts/resume-document.mjs. -->',
  '',
  `# ${resume.name}`,
  '',
  `**${headline}**`,
  '',
  [
    'Vancouver, BC',
    phone,
    `[${resume.email}](mailto:${resume.email})`,
    `[${resume.siteUrl.replace('https://', '')}](${resume.siteUrl})`,
    `[${github}](https://${github})`,
    `[${linkedIn}](https://${linkedIn})`,
  ].join(' | '),
  '',
  availability,
  '',
  section('Profile', profile),
  section('Skills', skills.map(([label, items]) => `- **${label}:** ${list(items)}`).join('\n')),
  section('Selected Projects', resume.projects.map(projectEntry).join('\n\n')),
  section('Experience', resume.experience.slice(0, 4).map(experienceEntry).join('\n\n')),
  section(
    'Education',
    resume.education
      .slice(0, 3)
      .map((item) => `- **${item.institution}:** ${item.credential} (${item.period})`)
      .join('\n'),
  ),
  section('Additional', additionalItems.map((item) => `- **${item.label}:** ${item.text}`).join('\n')),
  '',
]
  .join('\n\n')
  .replace(/\n{3,}/g, '\n\n');

await writeFile(outputPath, markdown, 'utf8');
console.log(`Wrote ${outputPath}`);
